// Browser-side reads of static JSON under public/data/. Static files are the
// one thing that works the same on GitHub Pages and Vercel; the only target
// difference is the basePath prefix. Nothing here is imported into a bundle as
// data: every file is fetched on demand and cached for the session.
//
// Two producers write these files, both from the committed snapshot:
//   - data-pipeline/build_medicines.py -> public/data/{medicines,kendras}/**
//     (read through lib/medicineShards.ts)
//   - scripts/build-search-index.mjs   -> public/data/search/*.json
//     (procedure, hospital and CGHS indexes and the bill checker's medicine
//     reference prices; generated by predev/prebuild, gitignored). The index
//     shapes below are that script's output contract: change both together.

import { BASE_PATH } from "./basePath";
import type { MedicineForm, MedicineRef } from "./types";

const cache = new Map<string, Promise<unknown>>();

/**
 * Fetch `${basePath}/data/${path}` once per session. A missing file or a bad
 * response resolves to `fallback` (and stays cached); a network error resolves
 * to `fallback` but is evicted, so the next call retries.
 */
export function fetchStaticJson<T>(path: string, fallback: T): Promise<T> {
  if (!cache.has(path)) {
    cache.set(
      path,
      fetch(`${BASE_PATH}/data/${path}`)
        .then((r) => (r.ok ? r.json() : fallback))
        .catch(() => {
          cache.delete(path); // network error: allow a retry
          return fallback;
        })
    );
  }
  return cache.get(path) as Promise<T>;
}

// ---- Search indexes (scripts/build-search-index.mjs) -----------------------

/** [slug, name, cityLow, cityHigh, number of hospital-wise prices] */
export type ProcedureIndexRow = [
  slug: string,
  name: string,
  low: number | null,
  high: number | null,
  hospitalCount: number,
];
/** HexaHealth market estimates; `date` comes from data/source-dates.json (null = not recorded). */
export type ProcedureIndex = { v: 1; date: string | null; p: ProcedureIndexRow[] };

/** [name, index into `c`/`l`, slug, pincode] */
export type HospitalIndexRow = [name: string, cityIndex: number, slug: string, pincode: string | null];
/** `c` = city URL slugs ("bangalore"), `l` = display names ("Bangalore"), same order. */
export type HospitalIndex = { v: 1; c: string[]; l: string[]; h: HospitalIndexRow[] };

/**
 * On the wire the slug is 0 when it equals hospitalSlug(name), which is true
 * for ~98% of rows (only de-duplicated "-2" slugs are spelled out). That
 * keeps the file near its ~40 KB gzipped budget. loadHospitalIndex() fills
 * the slugs back in, so every consumer sees HospitalIndex.
 */
type HospitalIndexWireRow = [name: string, cityIndex: number, slug: string | 0, pincode: string | null];
type HospitalIndexWire = { v: 1; c: string[]; l: string[]; h: HospitalIndexWireRow[] };

/**
 * The directory's slug rule: data-pipeline/build_static_data.py slugify()
 * (NFKD, drop non-ASCII, non-alphanumeric runs to "-", trim "-", lowercase).
 * scripts/build-search-index.mjs carries the same function and elides a slug
 * only when this rebuilds it exactly: change all three together.
 */
export function hospitalSlug(name: string): string {
  return name
    .normalize("NFKD")
    .replace(/[^\x00-\x7f]/g, "")
    .replace(/[^a-zA-Z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .toLowerCase();
}

/** Fills elided slugs in place (idempotent: the cached object is shared). */
function decodeHospitalIndex(idx: HospitalIndexWire): HospitalIndex {
  for (const row of idx.h) if (row[2] === 0) row[2] = hospitalSlug(row[0]);
  return idx as HospitalIndex;
}

/** [code, name, index into `s`, NABH 0|1, general, semi-private, private]; amounts are raw CGHS strings. */
export type CghsIndexRow = [
  code: string,
  name: string,
  specialtyIndex: number,
  nabh: 0 | 1,
  general: string | null,
  semi: string | null,
  priv: string | null,
];
/** CGHS Tier I rate list; `date` comes from data/source-dates.json (null = not recorded). */
export type CghsIndex = { v: 1; date: string | null; s: string[]; r: CghsIndexRow[] };

const EMPTY_PROCEDURES: ProcedureIndex = { v: 1, date: null, p: [] };
const EMPTY_HOSPITALS: HospitalIndex = { v: 1, c: [], l: [], h: [] };
const EMPTY_CGHS: CghsIndex = { v: 1, date: null, s: [], r: [] };

/** About 5 KB. Fetch on first focus of a search field, never on page load. */
export function loadProcedureIndex(): Promise<ProcedureIndex> {
  return fetchStaticJson("search/procedures.json", EMPTY_PROCEDURES);
}

/** About 36 KB gzipped. Fetch on first focus of a search field, never on page load. */
export function loadHospitalIndex(): Promise<HospitalIndex> {
  return fetchStaticJson<HospitalIndexWire>("search/hospitals.json", EMPTY_HOSPITALS).then(decodeHospitalIndex);
}

/** The full CGHS list. Fetch on first use, never on page load. */
export function loadCghsIndex(): Promise<CghsIndex> {
  return fetchStaticJson("search/cghs.json", EMPTY_CGHS);
}

/**
 * [slug, title, form, cheapest Jan Aushadhi per unit, NPPA ceiling per unit,
 * S.O. number, S.O. date]: the same slice as lib/medicines.ts getMedicineRefs().
 */
type MedicineRefWireRow = [
  slug: string,
  title: string,
  form: MedicineForm,
  jaPerUnit: number | null,
  ceiling: number | null,
  soNumber: string | null,
  soDate: string | null,
];
type MedicineRefWire = { v: 1; r: MedicineRefWireRow[] };

const EMPTY_MEDICINE_REFS: MedicineRefWire = { v: 1, r: [] };
let medicineRefs: Promise<MedicineRef[]> | null = null;

/**
 * The bill checker's reference prices (~1,400 rows, about 21 KB gzipped).
 * Fetched when the first bill line appears, never on page load, so they no
 * longer ride in /check-bill's HTML as props. An empty list means the fetch
 * failed; the next call retries.
 */
export function loadMedicineRefs(): Promise<MedicineRef[]> {
  if (!medicineRefs) {
    medicineRefs = fetchStaticJson("search/medicine-refs.json", EMPTY_MEDICINE_REFS).then((idx) => {
      const refs = idx.r.map(
        ([slug, title, form, jaPerUnit, ceiling, soNumber, soDate]): MedicineRef => ({
          slug,
          title,
          form,
          jaPerUnit,
          nppaCeiling:
            ceiling !== null ? { price: ceiling, soNumber: soNumber ?? "", soDate: soDate ?? "" } : null,
        })
      );
      if (refs.length === 0) medicineRefs = null;
      return refs;
    });
  }
  return medicineRefs;
}
